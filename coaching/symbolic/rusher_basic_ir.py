"""Bounded semantic IR <-> executable BASIC for the v16-derived rusher family.

The complete executable body is checked on extraction. This is an explicit
grounding, not an arbitrary Python/BASIC translator or an equivalence claim.
"""
from __future__ import annotations

import argparse
from dataclasses import asdict, dataclass
import json
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[2]
BODY = ROOT / "coaching/policies/basic-rusher/controller.bas"
SEMANTICS = BODY.with_name("semantics.md")


@dataclass(frozen=True)
class Rusher:
    holdBack: int = 16
    leadDiv: int = 30
    retreatPct: int = 40
    recoverUntilPct: int = 75
    curveEnabled: int = 1

    def validate(self):
        if any(type(value) is not int for value in asdict(self).values()):
            raise ValueError("Parameters must be integers")
        if not (4 <= self.holdBack <= 20 and 20 <= self.leadDiv <= 40
                and 20 <= self.retreatPct < self.recoverUntilPct <= 90
                and self.curveEnabled in (0, 1)):
            raise ValueError("Unsupported rusher parameters")
        return self


def block(policy: Rusher) -> str:
    return "```pudge-rusher-basic\n" + json.dumps(asdict(policy.validate()), indent=2) + "\n```\n"


def parse(text: str) -> Rusher:
    blocks = re.findall(r"```pudge-rusher-basic\n(.*?)\n```", text, re.S)
    if len(blocks) != 1:
        raise ValueError("Expected one pudge-rusher-basic block")
    def unique(pairs):
        result = {}
        for key, value in pairs:
            if key in result:
                raise ValueError(f"Duplicate parameter: {key}")
            result[key] = value
        return result
    values = json.loads(blocks[0], object_pairs_hook=unique)
    if not isinstance(values, dict) or set(values) != set(Rusher.__dataclass_fields__):
        raise ValueError("Missing or unknown parameter")
    policy = Rusher(**values).validate()
    if text.strip() != describe(policy).strip():
        raise ValueError("Unsupported semantic prose edit; update the grounding first")
    return policy


def describe(policy: Rusher) -> str:
    return SEMANTICS.read_text().rstrip() + "\n\n" + block(policy)


def generate(policy: Rusher) -> str:
    return "' Generated by coaching.symbolic.rusher_basic_ir; edit the semantic source.\n" + "".join(
        f"{key} = {value}\n" for key, value in asdict(policy.validate()).items()
    ) + "\n" + BODY.read_text()


def executable(code: str) -> list[str]:
    lines = []
    for line in code.splitlines():
        tokens = []
        offset = 0
        for match in re.finditer(r'"(?:[^"\n]|"")*"|\'[^\n]*|[^\s"\']+', line):
            if line[offset:match.start()].strip():
                raise ValueError("Malformed BASIC string")
            offset = match.end()
            token = match[0]
            if token.startswith("'"):
                break
            # BASIC keywords ignore case; emitted strings do not. Apostrophes
            # inside strings are data, not comments.
            tokens.append(token if token.startswith('"') else token.lower())
        if line[offset:].strip():
            raise ValueError("Malformed BASIC string")
        if tokens:
            lines.append(" ".join(tokens))
    return lines


def extract(code: str) -> Rusher:
    lines = executable(code)
    values = {}
    for key, line in zip(Rusher.__dataclass_fields__, lines):
        match = re.fullmatch(key.lower() + r" = (\d+)", line)
        if not match:
            raise ValueError("Unrecognized parameter assignment")
        values[key] = int(match[1])
    if len(values) != len(Rusher.__dataclass_fields__):
        raise ValueError("Missing parameter assignments")
    policy = Rusher(**values).validate()
    if lines != executable(generate(policy)):
        raise ValueError("Unsupported executable change; cannot recover this policy")
    return policy


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("direction", choices=("generate", "extract", "verify"))
    parser.add_argument("source", type=Path)
    parser.add_argument("output", type=Path, nargs="?")
    args = parser.parse_args()
    source = args.source.read_text()
    if args.direction == "generate":
        result = generate(parse(source))
    else:
        result = describe(extract(source))
    if args.output:
        args.output.write_text(result)
    else:
        print(result, end="")


if __name__ == "__main__":
    main()
